import { AssetViewer } from './AssetViewer';
import type { Asset } from '../lib/api';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
let tree: ReactTestRenderer;
afterEach(async () => { await act(async () => tree?.unmount()); });
it('opens a distant photo directly without requesting the previous session or first page', async () => {
  const item = { id: 'photo-22679', type: 'IMAGE', originalFileName: 'Last photo', localDateTime: '2026-11-20' } as Asset;
  const loadRange = vi.fn();
  const collection = { key: 'photos', total: 22680, version: 1, itemAt: (at: number) => at === 22679 ? item : undefined, loadRange };
  const render = (index: number | null) => <AssetViewer assets={[item]} serverUrl="https://photos.test" token={null} collection={collection} index={index} onClose={() => {}} onChanged={() => {}} />;
  await act(async () => { tree = create(render(null)); });
  expect(loadRange).not.toHaveBeenCalled();
  await act(async () => { tree.update(render(22679)); });
  expect(loadRange.mock.calls).toEqual([[22677, 22682]]);
  const list = tree.root.findByType('VirtualizedList' as any);
  expect(list.props.initialScrollIndex).toBe(22679);
  expect(list.props.getItemCount()).toBe(22680);
});
